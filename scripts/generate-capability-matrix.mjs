#!/usr/bin/env node
// Generates the sandbox capability matrix in docs/isolation.md from each
// adapter's exported capabilities. `--check` fails (exit 1) on drift so the
// committed matrix can never lie about what an adapter supports.
//
// Runs on Node 24 (type stripping): adapter sources are imported directly.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const isolationPath = path.join(repoRoot, "docs", "isolation.md");
const START = "<!-- capability-matrix:start (generated by scripts/generate-capability-matrix.mjs — do not edit by hand) -->";
const END = "<!-- capability-matrix:end -->";

const adapters = path.join(repoRoot, "packages", "sandbox", "src", "adapters");
const load = (rel) => import(path.join(adapters, rel));

async function collectRows() {
  const [box, namespace, selfhost, microsandbox, docker, local, fake, e2b, daytona, cloudflare, modal, catalog] =
    await Promise.all([
      load("box/capabilities.ts"),
      load("namespace/index.ts"),
      load("selfhost/index.ts"),
      load("microsandbox/index.ts"),
      load("docker/index.ts"),
      load("local/index.ts"),
      load("fake/index.ts"),
      load("e2b/index.ts"),
      load("daytona/index.ts"),
      load("cloudflare/index.ts"),
      load("modal/index.ts"),
      load("catalog/index.ts"),
    ]);

  const rows = [
    { id: "box", tier: "first-party", caps: box.BOX_CAPABILITIES },
    { id: "namespace", tier: "first-party", caps: namespace.NAMESPACE_CAPABILITIES },
    { id: "selfhost", tier: "first-party", caps: selfhost.SELFHOST_CAPABILITIES },
    { id: "microsandbox", tier: "first-party", caps: microsandbox.MICROSANDBOX_CAPABILITIES },
    { id: "e2b", tier: "first-party", caps: e2b.E2B_CAPABILITIES },
    { id: "daytona", tier: "first-party", caps: daytona.DAYTONA_CAPABILITIES },
    { id: "cloudflare", tier: "first-party", caps: cloudflare.CLOUDFLARE_CAPABILITIES },
    { id: "modal (gpu lane)", tier: "first-party", caps: modal.MODAL_CAPABILITIES },
    { id: "docker", tier: "first-party", caps: docker.DOCKER_CAPABILITIES },
    { id: "local", tier: "first-party", caps: local.LOCAL_CAPABILITIES },
    { id: "fake", tier: "first-party", caps: fake.FAKE_CAPABILITIES },
  ];
  for (const manifest of catalog.CATALOG_MANIFESTS) {
    const provider = catalog.createCatalogStub(manifest);
    rows.push({ id: manifest.id, tier: "catalog-stub", caps: await provider.capabilities() });
  }
  return rows;
}

const yn = (v) => (v ? "yes" : "no");

function renderMatrix(rows) {
  const header =
    "| provider | tier | isolation | snapshot | fork | stop/resume | ports | private ports | net policy | gpu | kvm | docker | max cmd (s) |";
  const divider = header.replace(/[^|]/g, "-").replace(/-\|/g, " |").replace(/\|-/g, "| ");
  const lines = [header, divider];
  for (const { id, tier, caps } of rows) {
    lines.push(
      `| ${id} | ${tier} | ${caps.isolation} | ${yn(caps.snapshot)} | ${yn(caps.fork)} | ${yn(caps.stop)}/${yn(caps.resume)} | ${yn(caps.ports)} | ${yn(caps.privatePorts)} | ${caps.networkPolicy} | ${yn(caps.gpu)} | ${yn(caps.kvm)} | ${yn(caps.docker)} | ${caps.maxCommandSeconds} |`,
    );
  }
  return lines.join("\n");
}

async function main() {
  const check = process.argv.includes("--check");
  const rows = await collectRows();
  const matrix = `${START}\n${renderMatrix(rows)}\n${END}`;

  let current = "";
  try {
    current = await readFile(isolationPath, "utf8");
  } catch {
    // missing docs/isolation.md is drift
  }
  const startIdx = current.indexOf(START);
  const endIdx = current.indexOf(END);
  const hasMarkers = startIdx !== -1 && endIdx !== -1;
  const next = hasMarkers
    ? current.slice(0, startIdx) + matrix + current.slice(endIdx + END.length)
    : `${current.trimEnd()}\n\n${matrix}\n`;

  if (check) {
    if (!hasMarkers || current !== next) {
      console.error("capability matrix drift: run `node scripts/generate-capability-matrix.mjs` and commit docs/isolation.md");
      process.exit(1);
    }
    console.log("capability matrix: no drift");
    return;
  }
  await writeFile(isolationPath, next);
  console.log(`wrote capability matrix (${rows.length} providers) to docs/isolation.md`);
}

await main();
